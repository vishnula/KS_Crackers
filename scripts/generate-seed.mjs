// Turns src/data/products.json into seed.sql for D1.
//   npm run db:seed:local    (writes seed.sql, applies to the local database)
//   npm run db:seed:remote   (applies to the deployed database)
//
// Insert-only. Existing rows are left completely alone, because by the time this
// is re-run the owner has been editing prices and stock in /admin and a reseed
// would silently undo his work - reverting live prices on the busiest night of
// the year. To push a whole new year's price list, use the CSV import in the
// admin panel: it validates every row and rejects the file if any row is wrong.

import { readFile, writeFile } from "node:fs/promises";

const q = (value) => `'${String(value).replace(/'/g, "''")}'`;

const products = JSON.parse(await readFile("src/data/products.json", "utf8"));

const rows = products.map((p, index) =>
  `(${p.code},${q(p.category)},${q(p.name)},${q(p.unit)},${p.mrp},${p.price},${index})`,
);

const sql = `-- Generated by scripts/generate-seed.mjs. Do not edit by hand.
INSERT INTO products (code, category, name, unit, mrp, price, sort_order)
VALUES
${rows.join(",\n")}
ON CONFLICT(code) DO NOTHING;
`;

await writeFile("seed.sql", sql);
console.log(`Wrote seed.sql with ${products.length} products`);
